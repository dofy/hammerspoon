--- === keystats ===
---
--- Records modifier-bearing keystrokes together with the frontmost
--- application, so shortcut usage can be analysed later with the `keystats`
--- CLI.
---
--- Design notes:
---  * The keyDown callback performs no OS calls. The frontmost app is kept up
---    to date by an `hs.application.watcher`; reading it (or an AX window
---    title) inside the hot path would add perceptible typing latency.
---  * Events are buffered in memory and flushed to SQLite in a single
---    transaction every `config.flushInterval` seconds. Identical events inside
---    one flush window collapse into a single row with a count.
---  * macOS silently disables an event tap whose callback is considered too
---    slow, so a watchdog timer re-enables the tap periodically.

local sqlite3 = require("hs.sqlite3")

local M = {}

M.config = {
    dbPath = os.getenv("HOME") .. "/.local/share/keystats/keystats.db",
    flushInterval = 5,
    watchdogInterval = 60,
    -- Record plain character keys too. This turns the module into a full
    -- keylogger (passwords included, outside secure input fields), so it is
    -- off by default; shortcut statistics do not need it.
    includePlainKeys = false,
    -- Count key repeats generated by holding a key down. Off by default,
    -- otherwise a held arrow key dominates every ranking.
    countAutorepeat = false,
    -- Combinations recorded even though they carry no cmd/alt/ctrl. Shift alone
    -- is normally capitalisation, but a few real hotkeys live there — Raycast
    -- defaults to shift+space. Keys are the canonical spelling this module
    -- writes: modifiers in ctrl+alt+shift+cmd order, then the key name from
    -- hs.keycodes.map, joined with '+'.
    alwaysRecord = { ["shift+space"] = true },
    -- Record Escape, the function keys and the navigation keys when pressed
    -- without cmd/alt/ctrl. Off by default: a bare arrow key is navigation,
    -- not a shortcut, and it buries the real combinations in every ranking.
    includeBareSpecialKeys = false,
    -- The live dashboard. Served by keystats/server.py as a child process, so a
    -- heavy query can never block the event tap the way an in-process server
    -- would. Loopback only: this database records every shortcut pressed.
    server = {
        enabled = true,
        host = "127.0.0.1",
        port = 8787,
        python = "/usr/bin/python3",
        -- Relaunch a server that exits on its own, up to this many times in a
        -- row. A port already taken by an earlier run is not worth retrying.
        maxRestarts = 3,
        restartDelay = 5,
    },
    -- A global hotkey is consumed before any app sees it, so the tap can only
    -- record whoever was frontmost. When a keystroke is followed by an app
    -- activation inside this many seconds, that target app is stored on the
    -- event as evidence that the combination was a global hotkey. Set to 0 to
    -- disable the probe. Measured on this machine: an app activation lands
    -- ~0.3s after the keystroke, so the window has to clear that; keep it well
    -- under a second or a deliberate manual app switch starts counting.
    globalSwitchWindow = 0.6,
    -- Set of bundleIDs that are never recorded, e.g.
    -- excludeApps = { ["com.apple.Passwords"] = true }
    excludeApps = {},
    debug = false,
}

-- Keys that count as a shortcut without cmd/alt/ctrl, but only when
-- config.includeBareSpecialKeys is on.
local SPECIAL_KEY_NAMES = {
    "escape", "home", "end", "pageup", "pagedown", "forwarddelete", "help",
    "left", "right", "up", "down",
    "f1", "f2", "f3", "f4", "f5", "f6", "f7", "f8", "f9", "f10",
    "f11", "f12", "f13", "f14", "f15", "f16", "f17", "f18", "f19", "f20",
}

local tap, flushTimer, watchdogTimer, appWatcher
local serverTask, serverRestarts, serverWanted = nil, 0, false
local db, stmts
local buffer, bufferCount = {}, 0
local appCache = {}
local specialKeys = {}
local keyNames = {}
local currentApp = { bundle = "unknown", name = "unknown" }
local lastKey = nil
local lastQuit = nil
local lastMark = nil
local prevShutdownCallback

local log = hs.logger.new("keystats", "info")

-- SQL ------------------------------------------------------------------

local SCHEMA = [[
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;

CREATE TABLE IF NOT EXISTS app (
    id        INTEGER PRIMARY KEY,
    bundle_id TEXT UNIQUE NOT NULL,
    name      TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS event (
    ts        INTEGER NOT NULL,
    app_id    INTEGER NOT NULL REFERENCES app(id),
    mods      TEXT NOT NULL,
    keycode   INTEGER NOT NULL,
    n         INTEGER NOT NULL DEFAULT 1,
    switch_to INTEGER REFERENCES app(id)   -- app activated right after the keystroke
);

CREATE TABLE IF NOT EXISTS keyname (
    keycode INTEGER PRIMARY KEY,
    name    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS event_ts     ON event(ts);
CREATE INDEX IF NOT EXISTS event_app_ts ON event(app_id, ts);
CREATE INDEX IF NOT EXISTS event_combo  ON event(mods, keycode);
]]

-- Created after the switch_to migration, never inside SCHEMA: on a database
-- that predates the column, CREATE TABLE IF NOT EXISTS is a no-op and the
-- index would be built against a column that is not there yet.
local SWITCH_INDEX = [[
CREATE INDEX IF NOT EXISTS event_switch ON event(switch_to) WHERE switch_to IS NOT NULL;
]]

-- Helpers --------------------------------------------------------------

-- Fixed order, so cmd+shift and shift+cmd never become two different rows.
-- The fn flag is deliberately dropped: macOS sets it on every arrow and
-- function key, which would make "fn" the most common modifier by far.
local function modsString(f)
    local parts = {}
    if f.ctrl  then parts[#parts + 1] = "ctrl"  end
    if f.alt   then parts[#parts + 1] = "alt"   end
    if f.shift then parts[#parts + 1] = "shift" end
    if f.cmd   then parts[#parts + 1] = "cmd"   end
    return table.concat(parts, "+")
end

local function appId(bundle, name)
    local id = appCache[bundle]
    if id then return id end
    stmts.insApp:bind_values(bundle, name)
    stmts.insApp:step()
    stmts.insApp:reset()
    stmts.selApp:bind_values(bundle)
    if stmts.selApp:step() == sqlite3.ROW then id = stmts.selApp:get_value(0) end
    stmts.selApp:reset()
    appCache[bundle] = id
    return id
end

-- Flush ----------------------------------------------------------------

local function flush()
    if bufferCount == 0 then return end
    local pending, pendingCount = buffer, bufferCount
    buffer, bufferCount = {}, 0

    db:exec("BEGIN IMMEDIATE")
    for _, row in pairs(pending) do
        local aid = appId(row.bundle, row.name)
        local sid = row.switchTo and appId(row.switchTo, row.switchName or row.switchTo) or nil
        stmts.insEvent:bind_values(row.ts, aid, row.mods, row.keycode, row.n, sid)
        stmts.insEvent:step()
        stmts.insEvent:reset()
    end
    local rc = db:exec("COMMIT")
    if rc ~= sqlite3.OK then
        db:exec("ROLLBACK")
        log.ef("flush failed (%s), dropped %d events", db:errmsg(), pendingCount)
    elseif M.config.debug then
        log.df("flushed %d rows", pendingCount)
    end
end

-- Hot path -------------------------------------------------------------

local function onKey(e)
    local f = e:getFlags()
    -- shift alone is capitalisation, not a shortcut — unless config.alwaysRecord
    -- names the exact combination.
    local hasMod = f.cmd or f.alt or f.ctrl
    local keycode = e:getKeyCode()
    local mods = modsString(f)

    local whitelisted = false
    if not hasMod and next(M.config.alwaysRecord) then
        local name = keyNames[keycode]
        if name then
            whitelisted = M.config.alwaysRecord[
                (mods == "" and name) or (mods .. "+" .. name)] or false
        end
    end

    if not (hasMod or whitelisted
            or (M.config.includeBareSpecialKeys and specialKeys[keycode])
            or M.config.includePlainKeys) then
        return false
    end
    if not M.config.countAutorepeat
        and e:getProperty(hs.eventtap.event.properties.keyboardEventAutorepeat) == 1 then
        return false
    end

    local bundle = currentApp.bundle
    if M.config.excludeApps[bundle] then return false end

    local ts = os.time()
    local k = ts .. "\0" .. bundle .. "\0" .. mods .. "\0" .. keycode

    local row = buffer[k]
    if row then
        row.n = row.n + 1
    else
        buffer[k] = {
            ts = ts, bundle = bundle, name = currentApp.name,
            mods = mods, keycode = keycode, n = 1,
        }
        bufferCount = bufferCount + 1
    end
    lastKey = { key = k, at = hs.timer.secondsSinceEpoch() }
    return false
end

-- Split one press off the buffered row and tag it with the app that just came
-- to the front. Called from the application watcher, so it only ever sees
-- keystrokes still sitting in the buffer: a press in the last fraction of a
-- second before a flush is missed, which is why this is evidence and not proof.
local function markSwitch(toBundle, toName)
    if not lastKey then return end
    local window = M.config.globalSwitchWindow
    if window <= 0 or (hs.timer.secondsSinceEpoch() - lastKey.at) > window then
        lastKey = nil
        return
    end
    local bkey = lastKey.key
    lastKey = nil
    local row = buffer[bkey]
    if not row or row.bundle == toBundle then return end

    -- Cmd-Q and friends end the frontmost app, and whatever was behind it comes
    -- forward. That activation is a consequence of closing something, not a
    -- hotkey summoning the target, so it is not evidence of anything.
    if lastQuit and (hs.timer.secondsSinceEpoch() - lastQuit.at) <= window
        and (lastQuit.bundle == row.bundle or lastQuit.name == row.name) then
        return
    end

    if row.n > 1 then
        row.n = row.n - 1
    else
        buffer[bkey] = nil
        bufferCount = bufferCount - 1
    end

    local sk = row.ts .. "\0" .. row.bundle .. "\0" .. row.mods .. "\0"
        .. row.keycode .. "\0SW\0" .. toBundle
    local srow = buffer[sk]
    if srow then
        srow.n = srow.n + 1
    else
        buffer[sk] = {
            ts = row.ts, bundle = row.bundle, name = row.name,
            mods = row.mods, keycode = row.keycode, n = 1,
            switchTo = toBundle, switchName = toName,
        }
        bufferCount = bufferCount + 1
    end
    lastMark = { skey = sk, bkey = bkey, at = hs.timer.secondsSinceEpoch(),
                 bundle = row.bundle, name = row.name, ts = row.ts,
                 mods = row.mods, keycode = row.keycode }
end

-- NSWorkspaceDidTerminateApplication arrives *after* the next app activates, so
-- a quit cannot be filtered out up front: by the time it is known, the keystroke
-- has already been tagged. Take the tag back instead. Only works while the row
-- is still buffered, which it is unless the quit lands across a flush boundary.
local function unmarkSwitch(bundle, name)
    if not lastMark then return end
    local grace = M.config.globalSwitchWindow + 1.0
    if (hs.timer.secondsSinceEpoch() - lastMark.at) > grace then
        lastMark = nil
        return
    end
    if lastMark.bundle ~= bundle and lastMark.name ~= name then return end

    local srow = buffer[lastMark.skey]
    if srow then
        if srow.n > 1 then
            srow.n = srow.n - 1
        else
            buffer[lastMark.skey] = nil
            bufferCount = bufferCount - 1
        end
        local row = buffer[lastMark.bkey]
        if row then
            row.n = row.n + 1
        else
            buffer[lastMark.bkey] = {
                ts = lastMark.ts, bundle = lastMark.bundle, name = lastMark.name,
                mods = lastMark.mods, keycode = lastMark.keycode, n = 1,
            }
            bufferCount = bufferCount + 1
        end
        if M.config.debug then
            log.df("unmarked switch for %s (quit)", tostring(lastMark.bundle))
        end
    end
    lastMark = nil
end

-- Context tracking -----------------------------------------------------

local function onAppEvent(name, event, app)
    if event == hs.application.watcher.terminated then
        -- bundleID() is often already nil on a dead application, so keep the
        -- name as well and match on either.
        local ok, bundle = pcall(function() return app and app:bundleID() end)
        lastQuit = { at = hs.timer.secondsSinceEpoch(),
                     bundle = (ok and bundle) or nil, name = name }
        unmarkSwitch((ok and bundle) or nil, name)
        return
    end
    if event == hs.application.watcher.activated then
        local bundle = app:bundleID() or name or "unknown"
        -- Mark before switching context: markSwitch reads the buffered row.
        markSwitch(bundle, name or bundle)
        currentApp = { bundle = bundle, name = name or "unknown" }
    end
end

-- Live dashboard -------------------------------------------------------

local startServer   -- forward declaration: the exit callback relaunches it

local function onServerExit(code, stdout, stderr)
    local out = ((stderr or "") .. (stdout or "")):gsub("%s+$", "")
    serverTask = nil
    if not serverWanted then return end

    if out:find("Address already in use") then
        log.w("dashboard port is already served by another process, not retrying")
        return
    end
    if serverRestarts >= M.config.server.maxRestarts then
        log.ef("dashboard exited %d times, giving up: %s", serverRestarts, out)
        return
    end
    serverRestarts = serverRestarts + 1
    log.wf("dashboard exited (code %s), restarting in %ds: %s",
        tostring(code), M.config.server.restartDelay, out)
    hs.timer.doAfter(M.config.server.restartDelay, function()
        if serverWanted then startServer() end
    end)
end

startServer = function()
    local cfg = M.config.server
    if serverTask and serverTask:isRunning() then return end

    local script = hs.configdir .. "/keystats/server.py"
    if not hs.fs.attributes(script) then
        log.ef("dashboard script missing: %s", script)
        return
    end

    serverTask = hs.task.new(cfg.python, onServerExit, {
        script,
        "--db", M.config.dbPath,
        "--template", hs.configdir .. "/keystats/report.html",
        "--host", cfg.host,
        "--port", tostring(cfg.port),
        -- A SIGTERM to Hammerspoon never reaches hs.shutdownCallback, so the
        -- child has to notice the parent is gone by itself.
        "--exit-with-parent",
    })
    if serverTask and serverTask:start() then
        log.f("dashboard on http://%s:%d", cfg.host, cfg.port)
    else
        log.e("could not start the dashboard task")
        serverTask = nil
    end
end

local function stopServer()
    serverWanted = false
    if serverTask then
        serverTask:terminate()
        serverTask = nil
    end
end

-- Lifecycle ------------------------------------------------------------

function M.start()
    M.stop()

    local dir = M.config.dbPath:match("^(.*)/[^/]+$")
    if dir then hs.execute("mkdir -p " .. ("%q"):format(dir)) end

    db = sqlite3.open(M.config.dbPath)
    if not db then
        log.ef("cannot open %s", M.config.dbPath)
        return M
    end
    if db:exec(SCHEMA) ~= sqlite3.OK then
        log.ef("schema failed: %s", db:errmsg())
        db:close(); db = nil
        return M
    end

    -- Migrate databases that still carry the dropped window-title dimension.
    local hasTitleCol = false
    for row in db:nrows("PRAGMA table_info(event)") do
        if row.name == "title_id" then hasTitleCol = true end
    end
    if hasTitleCol then
        if db:exec("ALTER TABLE event DROP COLUMN title_id") == sqlite3.OK then
            log.i("migrated: dropped event.title_id")
        else
            log.ef("dropping event.title_id failed: %s", db:errmsg())
        end
    end
    if db:exec("DROP TABLE IF EXISTS title") ~= sqlite3.OK then
        log.ef("dropping the title table failed: %s", db:errmsg())
    end

    -- Migrate databases created before switch_to existed.
    local hasSwitch = false
    for row in db:nrows("PRAGMA table_info(event)") do
        if row.name == "switch_to" then hasSwitch = true end
    end
    if not hasSwitch then
        if db:exec("ALTER TABLE event ADD COLUMN switch_to INTEGER REFERENCES app(id)") == sqlite3.OK then
            log.i("migrated: added event.switch_to")
        else
            log.ef("migration failed: %s", db:errmsg())
        end
    end
    if db:exec(SWITCH_INDEX) ~= sqlite3.OK then
        log.ef("switch index failed: %s", db:errmsg())
    end

    stmts = {
        insApp   = db:prepare("INSERT OR IGNORE INTO app(bundle_id, name) VALUES (?, ?)"),
        selApp   = db:prepare("SELECT id FROM app WHERE bundle_id = ?"),
        insEvent = db:prepare("INSERT INTO event(ts, app_id, mods, keycode, n, switch_to) VALUES (?, ?, ?, ?, ?, ?)"),
    }

    -- Refresh the keycode -> name map for the current layout, preferring the
    -- shortest spelling when several names share a keycode.
    local best = {}
    for name, code in pairs(hs.keycodes.map) do
        if type(name) == "string" and type(code) == "number" then
            if not best[code] or #name < #best[code] then best[code] = name end
        end
    end
    keyNames = best
    local insName = db:prepare("INSERT OR REPLACE INTO keyname(keycode, name) VALUES (?, ?)")
    db:exec("BEGIN")
    for code, name in pairs(best) do
        insName:bind_values(code, name); insName:step(); insName:reset()
    end
    db:exec("COMMIT")
    insName:finalize()

    specialKeys = {}
    for _, name in ipairs(SPECIAL_KEY_NAMES) do
        local code = hs.keycodes.map[name]
        if code then specialKeys[code] = true end
    end

    local front = hs.application.frontmostApplication()
    if front then
        currentApp = { bundle = front:bundleID() or front:name(), name = front:name() }
    end

    appWatcher = hs.application.watcher.new(onAppEvent):start()

    tap = hs.eventtap.new({ hs.eventtap.event.types.keyDown }, onKey):start()

    flushTimer = hs.timer.doEvery(M.config.flushInterval, flush)
    watchdogTimer = hs.timer.doEvery(M.config.watchdogInterval, function()
        if tap and not tap:isEnabled() then
            log.w("event tap was disabled by the system, restarting it")
            tap:start()
        end
    end)

    if M.config.server.enabled then
        serverWanted, serverRestarts = true, 0
        startServer()
    end

    prevShutdownCallback = hs.shutdownCallback
    hs.shutdownCallback = function()
        flush()
        stopServer()
        if prevShutdownCallback then prevShutdownCallback() end
    end

    log.i("started, writing to " .. M.config.dbPath)
    return M
end

function M.stop()
    stopServer()
    if tap then tap:stop(); tap = nil end
    if flushTimer then flushTimer:stop(); flushTimer = nil end
    if watchdogTimer then watchdogTimer:stop(); watchdogTimer = nil end
    if appWatcher then appWatcher:stop(); appWatcher = nil end
    if db then
        flush()
        for _, s in pairs(stmts or {}) do s:finalize() end
        stmts = nil
        db:close()
        db = nil
    end
    appCache = {}
    buffer, bufferCount = {}, 0
    lastKey, lastQuit, lastMark = nil, nil, nil
    return M
end

function M.toggle()
    if tap then M.stop() else M.start() end
    return M
end

--- Force a flush and report what is on disk. Useful from the Console.
function M.status()
    flush()
    local info = { running = tap ~= nil, enabled = tap and tap:isEnabled() or false,
                   buffered = bufferCount, db = M.config.dbPath,
                   dashboard = (serverTask and serverTask:isRunning())
                       and ("http://" .. M.config.server.host .. ":" .. M.config.server.port)
                       or false }
    local out = hs.execute(("/usr/bin/sqlite3 %q 'SELECT count(*), sum(n) FROM event'"):format(M.config.dbPath))
    info.events = (out or ""):gsub("%s+$", "")
    return info
end

return M
